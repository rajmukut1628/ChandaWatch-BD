export function translate(value, language = bengali) {
  if (typeof value !== "string") return value;
  if (!language) return reverse[value] || englishCodes[value] || value;
  const translated = translations[value] || codes[value] || value;
  if (/^Welcome, .+\.$/.test(translated))
    return translated.replace(/^Welcome, (.+)\.$/, "স্বাগতম, $1।");
  return cleanBengali(translated);
}
